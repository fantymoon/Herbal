//
// 形态：跨书整合。一期回答一个问题，答案来自整个语料库（701 种古籍），
// 而不是读某一本书的某一段。这条线存在的理由就是"整合"——
// 检索、辨别、溯源、对读、批判，这五件事脚本做不了，因为脚本不觉得它们矛盾。
//
// 本期的素材全部来自 TCM-Ancient-Books-master/，引文一律照录，出处随引文上屏。
// 检索方式：按关键词跨 701 个文件全文匹配（语料是 GB18030，ripgrep 搜不到中文）。
//
// 这一期真正讲的不是"古人错了"，而是一件更小、更锋利的事：
// **一个因为"长得像"而得来的名字，被后人读成了"因为"。**
//
// 时长由旁白决定，不由字数决定：npm run topic:voice -- tu-que dump 之后逐段合成，
// timeline 模式量出的总长就是片长。改旁白必须重新合成，字数只是粗估。

export type Quote = {
  /** 屏上大字，照录原文。 */
  text: string;
  /** 出处，随引文上屏。 */
  source: string;
};

export type Segment = {
  /** 旁白：被朗读，同时作为字幕。口语化，为耳朵写，不为眼睛写。 */
  narration: string;
  /** 屏上引文（不朗读）。 */
  quote?: Quote;
  /** 数据屏的大数字。没有它，role="stat" 的屏会只剩字幕。 */
  stat?: { value: string; unit: string; note: string };
  /**
   * 左侧证据位的参数。跨书整合的图形不是装饰：时间线让"这条说法跨了几个朝代"
   * 一眼可见，书影让"这真的是书上写的"一眼可见——后者是观众相信旁白的唯一理由。
   * 给了 file 就渲染书影，否则渲染时间线。
   */
  plate?: {
    /** 书影文件名（public/plates/ 下）。 */
    file?: string;
    /** 原图尺寸，用于换算缩放。 */
    natural?: { w: number; h: number };
    /** 显示区域（原图像素）。 */
    crop?: { x: number; y: number; w: number; h: number };
    /** 要框出的那一行（原图像素）。 */
    box?: { x: number; y: number; w: number; h: number };
    /** 时间线要点亮的那一本。 */
    highlight?: string;
    note?: string;
  };
  /** 这一屏的视觉角色。 */
  role?: "title" | "quote" | "stat" | "closing";
};

export type TopicContent = {
  id: string;
  /** 片名，也是那个问题。 */
  question: string;
  /** 副题，一句话说明这期在做什么。 */
  deck: string;
  /**
   * 收尾屏那句话。**曾经硬编码在渲染器里**，于是英文版照搬了中文。
   * 凡是会被观众读到的文字都归内容模块管——渲染器不该替作者说话。
   */
  closingLine: string;
  /** 封面底部那句。同一个理由。 */
  tagline: string;
  /** 时间线的朝代数据。不给则用内置的中文默认值。 */
  eras?: { dynasty: string; years: string; books: string[] }[];
  segments: Segment[];
  /** 这一期真正引用到的书，片尾列出。 */
  sources: string[];
  music: string;
  accent: string;
};


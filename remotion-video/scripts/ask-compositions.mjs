// 从 src/asks/ 生成 Composition 注册表。
//
// 为什么生成而不是手写：这一条线是按批次走的（一次写十集稿），手写注册表意味着
// 每加一集都要记得改第二个文件，而漏掉的表现是「渲染时找不到这个 Composition」——
// 一个只有走到渲染那一步才暴露的错误。生成之后，加一集就是加一个 YAML。
//
//   npm run ask:compositions
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repo = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const asksDir = path.join(repo, "src", "asks");
const target = path.join(asksDir, "Compositions.tsx");

const ids = fs
  .readdirSync(asksDir)
  .filter((f) => f.endsWith(".content.ts"))
  .map((f) => f.replace(/\.content\.ts$/, ""))
  .sort();

/** `dazao-ye` → `AskDazaoYe`；`wangbuliuxing` → `AskWangbuliuxing`。 */
const compositionId = (id) =>
  "Ask" + id.split("-").map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join("");

/** `dazao-ye` → `dazaoYe`，用作 import 的标识符。 */
const ident = (id) => id.replace(/-([a-z0-9])/g, (_, ch) => ch.toUpperCase());

const registered = [];
const skipped = [];
for (const id of ids) {
  if (!fs.existsSync(path.join(asksDir, `${id}.voice.ts`))) {
    // 没有配音就没有时长，也就没有 Composition。不报错——ask:voice 会负责合成，
    // 而 ask:check 会把「缺 voice」当成一条 FAIL 报出来。这里只是不注册它。
    skipped.push(id);
    continue;
  }
  registered.push(id);
}

const imports = registered
  .map(
    (id) =>
      `import { content as ${ident(id)} } from "./${id}.content";\n` +
      `import { voice as ${ident(id)}Voice } from "./${id}.voice";`,
  )
  .join("\n");

const compositions = registered
  .map(
    (id) => `    <Composition
      id="${compositionId(id)}"
      component={AskFilm}
      durationInFrames={${ident(id)}Voice.totalFrames}
      fps={30}
      width={1080}
      height={1920}
      defaultProps={{ content: ${ident(id)}, voice: ${ident(id)}Voice }}
    />`,
  )
  .join("\n");

const source = `// AUTO-GENERATED by scripts/ask-compositions.mjs — 不要手改。
// 加一集：在 asks/ 放 YAML，跑 ask:build 与 ask:voice，再跑本脚本。
// 系列总封面（AskSeriesCover）不是一集，但注册表只有这一份，所以它在这里固定注册。
import { Composition } from "remotion";
import { AskFilm } from "../ask-film";
import { AskSeriesCover } from "./series-cover-film";
${imports}

// 「本草一问」系列的 Composition 注册表。竖屏 1080x1920，时长来自 voice 模块
// （= 各段旁白实际秒数之和 + 每段尾部呼吸），不写在组件里。
export const AskCompositions: React.FC = () => (
  <>
${compositions}
    {/* 系列总封面：单帧图，\`npx remotion still AskSeriesCover out/asks/covers/…\` 出它。
        它没有旁白也没有时长，注册成 Composition 只是为了让 Studio 和 CI 都看得见它。 */}
    <Composition
      id="AskSeriesCover"
      component={AskSeriesCover}
      durationInFrames={1}
      fps={30}
      width={1080}
      height={1920}
    />
  </>
);
`;

fs.writeFileSync(target, source, "utf8");
console.log(`wrote src/asks/Compositions.tsx — ${registered.length} composition(s)`);
if (skipped.length > 0) {
  console.log(`not registered yet (no voice module): ${skipped.join(", ")}`);
}

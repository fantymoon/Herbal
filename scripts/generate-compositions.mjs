// Generate src/Composition.tsx from src/finished/*.tsx.
// Usage: npm run gen
// - Scans finished films, parses the exported component name and duration.
// - Preserves the existing registration order; appends new films (sorted) at the end.
// - Emits static <Composition id="..." ... /> literals so source-string tests keep passing.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(fileURLToPath(import.meta.url));
const finishedDir = path.join(root, "..", "src", "finished");
const outFile = path.join(root, "..", "src", "Composition.tsx");

const toKebab = (name) =>
  name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

const files = fs
  .readdirSync(finishedDir)
  .filter((f) => f.endsWith(".tsx"))
  .sort();

// Durations currently registered in Composition.tsx. Wrapper variants (e.g.
// angelica-fourth-film-real-photo.tsx reuses another film) carry no duration
// literal of their own: they inherit the registered value, never a guess.
const current = fs.readFileSync(outFile, "utf8");
const TEMPLATES = ["HerbalFeature", "HerbProfileTemplate", "FormulaShortTemplate"];
const currentDurations = new Map(
  [...current.matchAll(/<Composition\s+id="(\w+)"\s+component=\{\w+\}\s+durationInFrames=\{(\d+)\}/g)].map(
    (m) => [m[1], m[2]],
  ),
);

// id -> { component, kebab, duration }
const discovered = new Map();
for (const file of files) {
  const source = fs.readFileSync(path.join(finishedDir, file), "utf8");
  const exports = [...source.matchAll(/export const (\w+)/g)].map((m) => m[1]);
  const component =
    exports.filter((n) => /(Film|Photo)$/.test(n)).at(-1) ?? exports.at(-1);
  if (!component) {
    console.warn(`skip ${file}: no exported component found`);
    continue;
  }
  const fileDuration = source.match(/durationInFrames=\{(\d+)\}/)?.[1];
  discovered.set(component, {
    component,
    kebab: file.replace(/\.tsx$/, ""),
    duration: fileDuration ?? null,
    source,
  });
}

// Second pass: resolve durations for wrappers with no literal of their own.
// A wrapper renders another finished film (e.g. RealPhoto renders the base
// film), so it inherits that film's duration. Otherwise keep the registered
// value; only brand-new films fall back to 360.
const byKebab = new Map([...discovered.values()].map((d) => [d.kebab, d]));
const resolveDuration = (entry, seen = new Set()) => {
  if (entry.duration) {
    return entry.duration;
  }
  if (seen.has(entry.component)) {
    return null;
  }
  seen.add(entry.component);
  const localImports = [...entry.source.matchAll(/from "\.\/([\w-]+)"/g)].map((m) => m[1]);
  for (const kebab of localImports) {
    const target = byKebab.get(kebab);
    if (target && entry.source.includes(`<${target.component}`)) {
      const inherited = resolveDuration(target, seen);
      if (inherited) {
        return inherited;
      }
    }
  }
  return currentDurations.get(entry.component) ?? null;
};
for (const entry of discovered.values()) {
  if (!entry.duration) {
    entry.duration = resolveDuration(entry) ?? "360";
    console.warn(`no duration literal in ${entry.kebab}.tsx: using ${entry.duration}`);
  }
  delete entry.source;
}

// Preserve the existing registration order; append brand-new films (sorted) at the end.
const orderedIds = [...current.matchAll(/id="(\w+)"/g)]
  .map((m) => m[1])
  .filter((id) => !TEMPLATES.includes(id))
  .filter((id, i, arr) => arr.indexOf(id) === i);

for (const [id, info] of discovered) {
  const expectedKebab = toKebab(id);
  if (info.kebab !== expectedKebab) {
    console.warn(`name drift: ${id} lives in ${info.kebab}.tsx (expected ${expectedKebab}.tsx)`);
  }
  if (!orderedIds.includes(id)) {
    orderedIds.push(id);
  }
}

const missing = orderedIds.filter((id) => !discovered.has(id));
for (const id of missing) {
  console.warn(`pruning ${id}: file removed from src/finished/`);
}
const registeredIds = orderedIds.filter((id) => discovered.has(id));

const imports = registeredIds
  .map((id) => {
    const info = discovered.get(id);
    return `import { ${id} } from "./finished/${info.kebab}";`;
  })
  .join("\n");

const compositions = registeredIds
  .map(
    (id) => `      <Composition
        id="${id}"
        component={${id}}
        durationInFrames={${discovered.get(id).duration}}
        fps={30}
        width={1080}
        height={1920}
      />`,
  )
  .join("\n");

const output = `// AUTO-GENERATED by scripts/generate-compositions.mjs - do not edit by hand.
// Run \`npm run gen\` after adding/removing files in src/finished/.
import { Composition } from "remotion";
import { createHerbalVideoProps } from "./herbal-data";
import {
  FormulaShortTemplate,
  HerbProfileTemplate,
  HerbalFeature,
} from "./HerbalVisuals";
${imports}

export const HerbalCompositions: React.FC = () => {
  return (
    <>
      <Composition
        id="HerbalFeature"
        component={HerbalFeature}
        durationInFrames={220}
        fps={30}
        width={1280}
        height={720}
        defaultProps={createHerbalVideoProps()}
      />
      <Composition
        id="HerbProfileTemplate"
        component={HerbProfileTemplate}
        durationInFrames={120}
        fps={30}
        width={1280}
        height={720}
        defaultProps={createHerbalVideoProps()}
      />
      <Composition
        id="FormulaShortTemplate"
        component={FormulaShortTemplate}
        durationInFrames={180}
        fps={30}
        width={1080}
        height={1920}
        defaultProps={createHerbalVideoProps()}
      />
${compositions}
    </>
  );
};
`;

fs.writeFileSync(outFile, output);
console.log(`registered ${registeredIds.length} finished films -> src/Composition.tsx`);
